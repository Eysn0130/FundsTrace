#!/usr/bin/env python3
"""Generate deterministic v1 OpenAPI and TypeScript without private runtime state."""
import argparse
import json
import os
from pathlib import Path
import sys
import tempfile


ROOT = Path(__file__).resolve().parents[1]


def _references(value):
    if isinstance(value, dict):
        if "$ref" in value:
            yield value["$ref"].rsplit("/", 1)[-1]
        for nested in value.values():
            yield from _references(nested)
    elif isinstance(value, list):
        for nested in value:
            yield from _references(nested)


def build_contract():
    # Set before importing app/db. Never trust an inherited FUND_DATA_DIR.
    with tempfile.TemporaryDirectory(prefix="funds-trace-contract-") as sandbox:
        os.environ["FUND_DATA_DIR"] = str(Path(sandbox) / "data")
        os.environ["MPLCONFIGDIR"] = str(Path(sandbox) / "matplotlib")
        sys.path.insert(0, str(ROOT))
        from fastapi import FastAPI
        from app.api.v1 import router
        api = FastAPI(title="FundsTrace API", version="1.0.0")
        api.include_router(router)
        schema = api.openapi()
        schema["paths"] = {path: value for path, value in schema["paths"].items() if path.startswith("/api/v1/")}
        schemas = schema.get("components", {}).get("schemas", {})
        required, pending = set(), list(_references(schema["paths"]))
        while pending:
            name = pending.pop()
            if name in required:
                continue
            required.add(name)
            pending.extend(_references(schemas[name]))
        schema["components"] = {"schemas": {name: schemas[name] for name in sorted(required)}}
        return schema


def typescript_type(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    for operator, joiner in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        if operator in schema:
            return "(" + joiner.join(typescript_type(item) for item in schema[operator]) + ")"
    if "enum" in schema:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{typescript_type(schema.get('items', {}))}>"
    if kind == "object" or "properties" in schema:
        properties = schema.get("properties", {})
        required = schema.get("required", [])
        fields = [f"{json.dumps(name)}{'' if name in required else '?'}: {typescript_type(value)};"
                  for name, value in properties.items()]
        extra = schema.get("additionalProperties", False)
        if extra:
            fields.append(f"[key: string]: {typescript_type(extra) if isinstance(extra, dict) else 'unknown'};")
        return "{ " + " ".join(fields) + " }"
    if kind == "string":
        return "Blob" if schema.get("format") == "binary" or schema.get("contentMediaType") == "application/octet-stream" else "string"
    return {"number": "number", "integer": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def render_types(schema):
    lines = ["// Generated by scripts/export_api_contract.py. Do not edit.",
             "// IDs and fixed-point amounts are strings in the source OpenAPI schema.", ""]
    for name, model in schema["components"]["schemas"].items():
        lines.append(f"export type {name} = {typescript_type(model)};")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when generated contracts drift")
    options = parser.parse_args()
    schema = build_contract()
    outputs = {ROOT / "contracts/openapi-v1.json": json.dumps(schema, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
               ROOT / "contracts/api-v1.d.ts": render_types(schema)}
    drift = []
    for path, content in outputs.items():
        if options.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                drift.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if drift:
        print("API contract drift: " + ", ".join(drift), file=sys.stderr)
        return 1
    print("API contracts are current" if options.check else "Generated v1 OpenAPI and TypeScript contracts")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
